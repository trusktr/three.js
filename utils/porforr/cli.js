// CLI interface
const args = process.argv.slice(2);

if (args.length < 2) {
	console.log('Usage: porforr <input.js> <output.wasm>');
	console.log('Example: porforr src/math/Vector2.js build/Vector2.wasm');
	process.exit(1);
}

const [inputFile, outputFile] = args;

try {
	await compile(inputFile, outputFile);
} catch (error) {
	console.error('Error:', error.message);
	process.exit(1);
}
